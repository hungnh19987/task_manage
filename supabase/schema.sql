CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT NOT NULL UNIQUE CHECK (username = lower(username)),
    full_name     TEXT NOT NULL CHECK (length(trim(full_name)) > 0),
    password_hash TEXT NOT NULL,
    auth_version  INTEGER NOT NULL DEFAULT 0,
    role          TEXT NOT NULL CHECK (role IN ('ADMIN', 'MANAGER', 'STAFF')),
    is_active     INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at    TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    updated_at    TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS auth_version INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS tasks (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          TEXT NOT NULL CHECK (length(trim(title)) > 0),
    description    TEXT,
    task_type      TEXT NOT NULL CHECK (task_type IN ('DIRECT', 'TEAM', 'PERSONAL')),
    status         TEXT NOT NULL DEFAULT 'DRAFT'
                   CHECK (status IN ('DRAFT', 'PENDING_APPROVAL', 'REJECTED', 'IN_PROGRESS', 'REPORTED', 'PASSED', 'FAILED')),
    proposer_id    INTEGER NOT NULL REFERENCES users (id),
    lead_id        INTEGER REFERENCES users (id),
    approver_id    INTEGER REFERENCES users (id),
    deadline       TEXT,
    submitted_at   TEXT,
    approved_at    TEXT,
    reject_reason  TEXT,
    report_summary TEXT,
    completed_at   TEXT,
    eval_result    TEXT CHECK (eval_result IS NULL OR eval_result IN ('PASS', 'FAIL')),
    eval_comment   TEXT,
    evaluated_by   INTEGER REFERENCES users (id),
    evaluated_at   TEXT,
    created_at     TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    updated_at     TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    CHECK (eval_result IS NULL OR status IN ('PASSED', 'FAILED'))
);

CREATE TABLE IF NOT EXISTS task_members (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id        INTEGER NOT NULL REFERENCES tasks (id),
    user_id        INTEGER NOT NULL REFERENCES users (id),
    content        TEXT NOT NULL CHECK (length(trim(content)) > 0),
    quantity       REAL CHECK (quantity IS NULL OR quantity >= 0),
    unit           TEXT,
    done_quantity  REAL CHECK (done_quantity IS NULL OR done_quantity >= 0),
    progress       INTEGER NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
    result_report  TEXT,
    lead_comment   TEXT,
    created_at     TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    updated_at     TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    UNIQUE (task_id, user_id)
);

CREATE TABLE IF NOT EXISTS task_logs (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    INTEGER NOT NULL REFERENCES tasks (id),
    member_id  INTEGER,
    actor_id   INTEGER NOT NULL REFERENCES users (id),
    action     TEXT NOT NULL,
    detail     TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);

CREATE INDEX IF NOT EXISTS idx_tasks_status ON tasks (status);
CREATE INDEX IF NOT EXISTS idx_tasks_proposer ON tasks (proposer_id);
CREATE INDEX IF NOT EXISTS idx_tasks_lead ON tasks (lead_id);
CREATE INDEX IF NOT EXISTS idx_tasks_deadline ON tasks (deadline);
CREATE INDEX IF NOT EXISTS idx_members_user ON task_members (user_id);
CREATE INDEX IF NOT EXISTS idx_logs_task_created ON task_logs (task_id, created_at);

CREATE OR REPLACE FUNCTION prevent_task_logs_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'task_logs là nhật ký bất biến: không được sửa hoặc xóa.';
END;
$$;

DROP TRIGGER IF EXISTS trg_task_logs_immutable ON task_logs;
CREATE TRIGGER trg_task_logs_immutable
BEFORE UPDATE OR DELETE ON task_logs
FOR EACH ROW EXECUTE FUNCTION prevent_task_logs_mutation();